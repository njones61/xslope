"""Regenerate the LEM sample SOLUTION and SEARCH figures in docs/lem/sample_images/.

Each figure is rebuilt with Spencer's method at the same num_slices and surface
type as the problem's ``<!-- test: ... -->`` tag, so the factor of safety drawn
on the figure matches the per-method table generated by gen_fs_tables.py.

Mapping: the file is split on test tags; the figures named ``*_results*.png`` and
``*_search_results*.png`` in the text segment preceding each tag belong to that
problem (so base vs *_mods variants land in separate segments).

A figure named ``*_solutions.png`` in the segment preceding a **paired** tag (one
carrying ``file2``, e.g. the gamma_sat zoned/sidecar equivalence pair) is built
instead as a single stacked figure: one solution panel per formulation, captioned
from PAIR_LABELS, so the two factors of safety are read side by side.

    PYTHONPATH=. python3 benchmarks/build_lem_figures.py            # every figure
    PYTHONPATH=. python3 benchmarks/build_lem_figures.py gsat_      # names matching
"""
import contextlib
import io
import os
import re
import tempfile

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from xslope.fileio import load_slope_data
from xslope.slice import generate_slices
from xslope.search import circular_search, noncircular_search
from xslope.solve import solve_selected
from xslope.plot import plot_solution, plot_circular_search_results, plot_noncircular_search_results

SAMPLES_MD = "docs/lem/samples.md"
IMG_DIR = "docs/lem"
METHOD = "spencer"

TEST_RE = re.compile(r'<!--\s*test:\s*(.*?)\s*-->')
RESULT_RE = re.compile(r'sample_images/([a-z0-9_]*?_results\d*)\.png')
SEARCH_RE = re.compile(r'sample_images/([a-z0-9_]*?_search_results\d*)\.png')
PAIR_RE = re.compile(r'sample_images/([a-z0-9_]*?_solutions)\.png')

# Panel captions for paired-formulation figures, keyed on the input file's stem.
PAIR_LABELS = {
    "xslope_gsat_zoned": "(a) zoned: two material polygons split at the water table, "
                         "γ = 120 above / 127 below",
    "xslope_gsat_sidecar": "(b) sidecar: one material, γ = 120 / γ_sat = 127 "
                           "with the same line on the piezo sheet, u = none",
}


def capture(path, fn, *args, **kwargs):
    """Run a plotting function and save whatever it would show to `path`."""
    saved = []

    def _show(*a, **k):
        plt.gcf().savefig(path, dpi=200, bbox_inches="tight")
        saved.append(path)
        plt.close("all")

    orig = plt.show
    plt.show = _show
    try:
        with contextlib.redirect_stdout(io.StringIO()):
            fn(*args, **kwargs)
        if not saved:
            plt.gcf().savefig(path, dpi=200, bbox_inches="tight")
            plt.close("all")
    finally:
        plt.show = orig
    print("wrote", path)


def search(sd, ttype, num_slices, rapid=False):
    """Return (crit, fs_cache, search_path, circle_cache) for the problem."""
    with contextlib.redirect_stdout(io.StringIO()):
        if ttype == "single_circle":
            ok, res = generate_slices(sd, circle=sd["circles"][0], num_slices=num_slices)
            slice_df, surface = res
            result = solve_selected(METHOD, slice_df, rapid=rapid)
            crit = {"slices": slice_df, "failure_surface": surface, "solver_result": result}
            return crit, None, None, None
        elif ttype == "noncircular_search":
            fs_cache, _, path = noncircular_search(sd, METHOD, num_slices=num_slices, diagnostic=False, rapid=rapid)
            return fs_cache[0], fs_cache, path, None
        else:
            fs_cache, _, path, circ = circular_search(sd, METHOD, num_slices=num_slices, diagnostic=False, rapid=rapid)
            return fs_cache[0], fs_cache, path, circ


def pair_figure(path, xlsx_files, num_slices, rapid=False):
    """Stack one solution panel per formulation of a paired model into `path`.

    Each panel is the file's own critical surface at `num_slices`, captioned with
    the formulation it was built from above the solver's own FS title, so the two
    factors of safety are compared without leaving the figure.
    """
    from PIL import Image

    tiles = []
    with tempfile.TemporaryDirectory() as td:
        for i, xlsx in enumerate(xlsx_files):
            sd = load_slope_data(xlsx)
            crit, _, _, _ = search(sd, "circular_search", num_slices, rapid)
            stem = os.path.splitext(os.path.basename(xlsx))[0]
            fig = plt.figure(figsize=(12, 7))
            with contextlib.redirect_stdout(io.StringIO()):
                plot_solution(sd, crit["slices"], crit["failure_surface"],
                              crit["solver_result"], fig=fig)
            ax = fig.axes[0]
            ax.set_title(f"{PAIR_LABELS.get(stem, stem)}\n{ax.get_title()}")
            tile = os.path.join(td, f"panel{i}.png")
            fig.savefig(tile, dpi=200, bbox_inches="tight")
            plt.close(fig)
            tiles.append(Image.open(tile).convert("RGB"))

        width = max(t.width for t in tiles)
        canvas = Image.new("RGB", (width, sum(t.height for t in tiles)), "white")
        y = 0
        for t in tiles:
            canvas.paste(t, ((width - t.width) // 2, y))
            y += t.height
        canvas.save(path)
    print("wrote", path)


def main(only=()):
    with open(SAMPLES_MD) as f:
        content = f.read()

    def wanted(names):
        """Keep the figure names matching a command-line filter (all, by default)."""
        return [x for x in names if not only or any(s in x for s in only)]

    # Segment boundaries: text before each test tag belongs to that tag's problem.
    last = 0
    n = 0
    for m in TEST_RE.finditer(content):
        segment = content[last:m.start()]
        last = m.end()
        params = dict(p.split("=", 1) for p in (kv.strip() for kv in m.group(1).split(",")) if "=" in p)
        xlsx = os.path.join(IMG_DIR, params["file"])
        ttype = params.get("type", "circular_search")
        num_slices = int(params.get("num_slices", 40))
        rapid = str(params.get("rapid", "false")).strip().lower() in ("true", "1", "yes")
        # RESULT_RE also matches *_search_results* (they contain "_results"); drop those.
        results = wanted(r for r in RESULT_RE.findall(segment) if "search_results" not in r)
        searches = wanted(SEARCH_RE.findall(segment))
        pairs = wanted(PAIR_RE.findall(segment)) if "file2" in params else []
        for name in pairs:
            pair_figure(f"{IMG_DIR}/sample_images/{name}.png",
                        [xlsx, os.path.join(IMG_DIR, params["file2"])],
                        num_slices, rapid)
            n += 1
        if not results and not searches:
            continue
        sd = load_slope_data(xlsx)
        crit, fs_cache, path, circ = search(sd, ttype, num_slices, rapid)
        for name in searches:
            out = f"{IMG_DIR}/sample_images/{name}.png"
            if ttype == "noncircular_search":
                capture(out, plot_noncircular_search_results, sd, fs_cache, path)
            else:
                capture(out, plot_circular_search_results, sd, fs_cache, path, circle_cache=circ)
            n += 1
        for name in results:
            out = f"{IMG_DIR}/sample_images/{name}.png"
            capture(out, plot_solution, sd, crit["slices"], crit["failure_surface"], crit["solver_result"])
            n += 1
    print(f"\nregenerated {n} sample figures")


if __name__ == "__main__":
    import sys
    main(only=tuple(sys.argv[1:]))
