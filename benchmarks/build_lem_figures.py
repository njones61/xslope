"""Regenerate the LEM sample INPUTS, SOLUTION and SEARCH figures in
docs/lem/sample_images/.

Each solution figure is rebuilt with Spencer's method at the same num_slices and
surface type as the problem's ``<!-- test: ... -->`` tag, so the factor of safety
drawn on the figure matches the per-method table generated by gen_fs_tables.py.
An inputs figure is the model itself — geometry, profile lines, loads, circles,
and the seepage mesh where the model carries one — so it is drawn from the
workbook alone, with no solve. It is framed to its content, which is how the
report draws the same view: equal aspect with the axes box at the model's true
proportions and one uniform cushion around it, rather than the data limits padded
out to fill an arbitrary figure aspect. On a section 750 ft wide and 180 ft tall
the latter put a third of the panel's height in empty ground below the model and
another third above it.

Mapping: the file is split on test tags; the figures named ``*_inputs*.png``,
``*_results*.png`` and ``*_search_results*.png`` in the text segment preceding
each tag belong to that problem (so base vs *_mods variants land in separate
segments). A figure that another page shows but no sample section does is listed
in ``EXTRA_FIGURES`` below and drawn from that entry instead.

    PYTHONPATH=. python3 benchmarks/build_lem_figures.py            # every figure
    PYTHONPATH=. python3 benchmarks/build_lem_figures.py gsat_      # names matching
    PYTHONPATH=. python3 benchmarks/build_lem_figures.py _inputs    # the models only

The last runs no solve at all: no solution or search figure is named ``_inputs``,
so every problem's search is skipped.
"""
import contextlib
import io
import os
import re

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from xslope.fileio import load_slope_data
from xslope.slice import generate_slices
from xslope.search import (circular_search, noncircular_search, file_search_window,
                           noncircular_search_opts)
from xslope.solve import solve_selected
from xslope.plot import (plot_inputs, plot_solution, plot_circular_search_results,
                         plot_noncircular_search_results)

SAMPLES_MD = "docs/lem/samples.md"
IMG_DIR = "docs/lem"
METHOD = "spencer"

TEST_RE = re.compile(r'<!--\s*test:\s*(.*?)\s*-->')
RESULT_RE = re.compile(r'sample_images/([a-z0-9_]*?_results\d*)\.png')
SEARCH_RE = re.compile(r'sample_images/([a-z0-9_]*?_search_results\d*)\.png')
INPUTS_RE = re.compile(r'sample_images/([a-z0-9_]*?_inputs\d*)\.png')

#: Figures on this page that another script draws, and which this one must
#: therefore leave alone: a file with two producers is a file with none, and the
#: second one to run decides what the page shows. The Hassiotis model's inputs
#: figure is drawn beside its three pile-row solutions by
#: benchmarks/make_hassiotis_figures.py, which is where that set belongs.
OTHER_OWNERS = {"hassiotis_inputs"}

#: Figures in sample_images/ that no sample section shows any more but another
#: page still does. They have no test tag to be read off, so they are drawn from
#: an explicit entry here rather than losing their producer: a figure nothing can
#: rebuild goes stale the first time the solver moves and nobody can tell.
#: Each entry is (figure name, workbook, test type, num_slices, kind, rapid),
#: where kind is "inputs", "results" or "search_results" — the same three the
#: page-driven pass draws, with the same styling.
#:
#: noncircular_search_results is the non-circular coordinate-descent search on
#: the weak-layer model. It was sample section 7's search figure until that
#: section shrank to its solution and table; docs/lem/search.md shows it as the
#: illustration of plot_noncircular_search_results().
EXTRA_FIGURES = [
    ("noncircular_search_results", "files/xslope_noncircular.xlsx",
     "noncircular_search", 40, "search_results", False),
]


def capture(path, fn, *args, **kwargs):
    """Run a plotting function and save whatever it would show to `path`."""
    saved = []

    def _show(*a, **k):
        plt.gcf().savefig(path, dpi=200, bbox_inches="tight")
        saved.append(path)
        plt.close("all")

    orig = plt.show
    plt.show = _show
    try:
        with contextlib.redirect_stdout(io.StringIO()):
            fn(*args, **kwargs)
        if not saved:
            plt.gcf().savefig(path, dpi=200, bbox_inches="tight")
            plt.close("all")
    finally:
        plt.show = orig
    print("wrote", path)


def search(sd, ttype, num_slices, rapid=False):
    """Return (crit, fs_cache, search_path, circle_cache) for the problem.

    A model that declares a search window on its circles sheet gets it: the
    figure has to draw the surface the problem is about, and an unwindowed
    search on a windowed model finds a different mechanism at a different factor
    of safety from the one the page's table and lock report.
    """
    win = file_search_window(sd)
    with contextlib.redirect_stdout(io.StringIO()):
        if ttype == "single_circle":
            ok, res = generate_slices(sd, circle=sd["circles"][0], num_slices=num_slices)
            slice_df, surface = res
            result = solve_selected(METHOD, slice_df, rapid=rapid)
            crit = {"slices": slice_df, "failure_surface": surface, "solver_result": result}
            return crit, None, None, None
        elif ttype == "noncircular_search":
            fs_cache, _, path = noncircular_search(sd, METHOD, num_slices=num_slices, diagnostic=False, rapid=rapid,
                                                  **noncircular_search_opts(win))
            return fs_cache[0], fs_cache, path, None
        else:
            fs_cache, _, path, circ = circular_search(sd, METHOD, num_slices=num_slices, diagnostic=False, rapid=rapid,
                                                     **win)
            return fs_cache[0], fs_cache, path, circ


def main(only=()):
    with open(SAMPLES_MD) as f:
        content = f.read()

    def wanted(names):
        """Keep the figure names matching a command-line filter (all, by default)."""
        return [x for x in names if not only or any(s in x for s in only)]

    # Segment boundaries: text before each test tag belongs to that tag's problem.
    last = 0
    n = 0
    for m in TEST_RE.finditer(content):
        segment = content[last:m.start()]
        last = m.end()
        params = dict(p.split("=", 1) for p in (kv.strip() for kv in m.group(1).split(",")) if "=" in p)
        xlsx = os.path.join(IMG_DIR, params["file"])
        ttype = params.get("type", "circular_search")
        num_slices = int(params.get("num_slices", 40))
        rapid = str(params.get("rapid", "false")).strip().lower() in ("true", "1", "yes")
        # RESULT_RE also matches *_search_results* (they contain "_results"); drop those.
        results = wanted(r for r in RESULT_RE.findall(segment) if "search_results" not in r)
        searches = wanted(SEARCH_RE.findall(segment))
        inputs = [x for x in wanted(INPUTS_RE.findall(segment))
                  if x not in OTHER_OWNERS]
        if not results and not searches and not inputs:
            continue
        sd = load_slope_data(xlsx)
        for name in inputs:
            # frame="content": equal aspect with the axes BOX at the model's true
            # proportions and a single uniform cushion around it, in data units on
            # both axes. The default framing keeps the box and pads the DATA out to
            # fill it, which on a wide-thin section is most of the panel in empty
            # ground. The excess figure height becomes an outer margin that the
            # tight bounding box below crops away.
            capture(f"{IMG_DIR}/sample_images/{name}.png", plot_inputs, sd,
                    frame="content")
            n += 1
        # The model's own figure needs no solution; don't run one for it.
        if not results and not searches:
            continue
        crit, fs_cache, path, circ = search(sd, ttype, num_slices, rapid)
        for name in searches:
            out = f"{IMG_DIR}/sample_images/{name}.png"
            if ttype == "noncircular_search":
                capture(out, plot_noncircular_search_results, sd, fs_cache, path)
            else:
                capture(out, plot_circular_search_results, sd, fs_cache, path, circle_cache=circ)
            n += 1
        for name in results:
            out = f"{IMG_DIR}/sample_images/{name}.png"
            capture(out, plot_solution, sd, crit["slices"], crit["failure_surface"], crit["solver_result"])
            n += 1

    for name, xlsx, ttype, num_slices, kind, rapid in EXTRA_FIGURES:
        if not wanted([name]):
            continue
        sd = load_slope_data(os.path.join(IMG_DIR, xlsx))
        out = f"{IMG_DIR}/sample_images/{name}.png"
        if kind == "inputs":
            capture(out, plot_inputs, sd, frame="content")
            n += 1
            continue
        crit, fs_cache, path, circ = search(sd, ttype, num_slices, rapid)
        if kind == "search_results":
            if ttype == "noncircular_search":
                capture(out, plot_noncircular_search_results, sd, fs_cache, path)
            else:
                capture(out, plot_circular_search_results, sd, fs_cache, path, circle_cache=circ)
        else:
            capture(out, plot_solution, sd, crit["slices"], crit["failure_surface"], crit["solver_result"])
        n += 1

    print(f"\nregenerated {n} sample figures")


if __name__ == "__main__":
    import sys
    main(only=tuple(sys.argv[1:]))
